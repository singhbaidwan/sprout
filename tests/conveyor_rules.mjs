import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const load=async file=>import(`data:text/javascript;base64,${Buffer.from(readFileSync(new URL(file,import.meta.url),'utf8')).toString('base64')}`);
const {autoPath,pathProblem,padAllowed,endpoints,conveyorStatus,describeConveyorPad,committedStock,intakeStatus,policyProblem}=await load('../static/conveyor-rules.js');
const {validatePositions}=await load('../static/layout-rules.js');
const catalog={entities:{chest:{x:0,y:6},mill:{x:3,y:6},oven:{x:6,y:6},depot:{x:7,y:3}},
  recycling:{entities:{well:{x:0,y:0},composter:{x:1,y:5},mixer:{x:5,y:5}}},
  field:{width:6,height:4},obstacles:[[6,2],[6,3],[3,4]],layout:{movable:['mill','oven','composter','mixer']},
  conveyors:{max_path:32,routes:{grain:{source:'chest',target:'mill'},flour:{source:'mill',target:'oven'},bread:{source:'oven',target:'depot'}}}};
const state={scenario:'factory',machines:{mill:{input:0},oven:{input:0}}};
const original=JSON.stringify(catalog);
assert.deepEqual(autoPath(state,catalog,'grain'),[48,49,50,51]);
assert.deepEqual(autoPath(state,catalog,'flour'),[51,52,53,54]);
assert.deepEqual(autoPath(state,catalog,'bread'),[54,55,47,39,31]);
for(const name of ['grain','flour','bread'])assert.equal(pathProblem(state,catalog,name,autoPath(state,catalog,name)),null);
for(const path of [[48],[48,51],[48,49,48,49,50,51],[48,40,41,42,43,51],[48,true,50,51]])assert.ok(pathProblem(state,catalog,'grain',path));
assert.equal(padAllowed(state,catalog,'grain',41),false); // Reserved composter.
const compact={...state,layout:{positions:{mill:{x:1,y:6},oven:{x:2,y:6}}}};
assert.deepEqual(endpoints(compact,catalog,'grain'),[48,49]);
assert.deepEqual(autoPath(compact,catalog,'flour'),[49,50]);
const built={...state,conveyors:{enabled:true,routes:{grain:{path:[48,49,50,51],feeding:true,slots:[1,0,0]}}}};
assert.equal(conveyorStatus(built,'grain'),'Moving');
assert.equal(describeConveyorPad(built,catalog,1,6),'grain conveyor · empty segment');
assert.equal(conveyorStatus({...built,chest:{wheat:12},conveyors:{enabled:true,routes:{grain:{feeding:true,slots:[0,0,0]}}}},'grain'),'Ready · feed on');
assert.equal(conveyorStatus({...built,conveyors:{...built.conveyors,enabled:false}},'grain'),'Paused · queue kept');
assert.equal(conveyorStatus({...built,machines:{mill:{input:12}},conveyors:{enabled:true,routes:{grain:{feeding:true,slots:[1,1,1]}}}},'grain'),'Blocked · input full');
assert.ok(validatePositions(built,catalog,{mill:{x:1,y:6}}));
assert.equal(validatePositions(built,catalog,{}),null);
assert.equal(JSON.stringify(catalog),original);
const branchCatalog={...catalog,conveyors:{...catalog.conveyors,routes:{...catalog.conveyors.routes,bread_store:{source:'oven',target:'chest',item:'bread'}}}};
const branchState={...state,chest:{wheat:12,bread:3},machines:{...state.machines,oven:{input:0,output:4,remaining:0}},conveyors:{enabled:true,routing:{mode:'store',next:'bread'},routes:{bread:{path:[54,55,47,39,31],slots:[0,0,0,0],feeding:true},bread_store:{path:[54,62,61,60,59,58,57,56,48],slots:[1,0,0,0,0,0,0,0],feeding:true,policy:{version:1,reserve:0,target:4}}}}};
assert.equal(pathProblem(branchState,branchCatalog,'bread_store',autoPath(branchState,branchCatalog,'bread_store')),null);
assert.equal(committedStock(branchState,'bread_store'),4);
assert.equal(intakeStatus(branchState,'bread'),'routing_hold');
assert.equal(conveyorStatus(branchState,'bread'),'Holding · other bread branch selected');
assert.equal(intakeStatus(branchState,'bread_store'),'target_met');
assert.equal(policyProblem('bread_store',0,48),null);
assert.ok(policyProblem('bread_store',0,49));
branchState.chest.wheat=45;
branchState.conveyors.routes.bread_store.slots=[1,1,1,1,1,1,1,1];
assert.equal(conveyorStatus(branchState,'bread_store'),'Blocked · chest full');
const governed={...state,chest:{wheat:4},machines:{mill:{input:0,remaining:0},oven:{input:0,remaining:0}},conveyors:{enabled:true,routes:{grain:{feeding:true,path:[48,49,50,51],slots:[0,0,0],policy:{version:1,reserve:4,target:6}}}}};
assert.equal(intakeStatus(governed,'grain'),'reserve_held');
assert.equal(conveyorStatus(governed,'grain'),'Holding · reserve kept');
assert.equal(committedStock(governed,'grain'),0);
governed.chest.wheat=12;governed.machines.mill={input:2,remaining:3};governed.conveyors.routes.grain.slots=[1,1,0];
assert.equal(committedStock(governed,'grain'),6);
assert.equal(intakeStatus(governed,'grain'),'target_met');
assert.equal(conveyorStatus(governed,'grain'),'Moving');
governed.conveyors.routes.grain.feeding=false;
assert.equal(intakeStatus(governed,'grain'),'feed_off');
assert.equal(policyProblem('grain',4,6),null);
assert.equal(policyProblem('bread',1,null),null);
for(const [name,reserve,target] of [['grain',true,6],['grain',49,6],['grain',4,true],['flour',9,3],['bread',0,1],['flour',0,-1]])assert.ok(policyProblem(name,reserve,target));
console.log('Conveyor paths, reserved pads, custom layouts, queues and relocation guards passed.');
